# Автомат обрабатывает натуральное число N по следующему алгоритму:
# 1. Строится двоичная запись числа N.
# 2. Если N чётное, то справа дописывается 10;
#    Если N нечётное, то слева дописывается 1, а справа 00.
# 3. Результат переводится в десятичную систему и выводится на экран.
#
# Укажите наименьшее число N, при котором результат работы
# автомата будет больше 107.
# ==========================================================

for n in range(1, 1000):  # Перебираем натуральные числа от 1 до 999
    s = bin(n)[2:]  # Переводим число n в двоичную систему

    if n % 2 == 0:  # Если число чётное
        s += '10'  # Дописываем справа 10
    else:  # Если число нечётное
        s = '1' + s + '00'  # Дописываем слева 1, справа 00

    r = int(s, 2)  # Переводим результат в десятичную систему

    if r > 107:  # Проверяем, больше ли результат 107
        print(n)  # Выводим исходное число N
        break  # Останавливаем программу, так как нашли минимум


