# 1. Переводим 1011,01 (2-чная) в 10-чную
num1 = int('1011', 2) + int('01', 2) / 2**2   # 11 + 1/4 = 11.25

# 2. Переводим 24,6 (8-чная) в 10-чную
num2 = int('24', 8) + int('6', 8) / 8**1      # 20 + 6/8 = 20.75

# 3. Складываем и переводим в 16-ричную
answer = hex(int(num1 + num2))[2:]            # 32 -> '20'

print(answer)  # 20